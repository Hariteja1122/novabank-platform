CREATE INDEX NB_ACCT.IX_AUDIT_OCCURRED ON NB_ACCT.AUDIT_LOG (OCCURRED_AT DESC);
CREATE INDEX NB_ACCT.IX_AUDIT_ACTOR    ON NB_ACCT.AUDIT_LOG (ACTOR_ID, OCCURRED_AT DESC);
CREATE INDEX NB_ACCT.IX_AUDIT_ACTION   ON NB_ACCT.AUDIT_LOG (ACTION, OCCURRED_AT DESC);

-- ---------------------------------------------------------------------
-- transaction-service
-- ---------------------------------------------------------------------
CREATE TABLE NB_TXN.TRANSACTIONS (
    ID               BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    REFERENCE        VARCHAR(24)   NOT NULL,
    IDEMPOTENCY_KEY  VARCHAR(64)   NOT NULL,
    TXN_TYPE         VARCHAR(12)   NOT NULL,
    FROM_ACCOUNT     VARCHAR(12),
    TO_ACCOUNT       VARCHAR(12)   NOT NULL,
    AMOUNT           DECIMAL(15,2) NOT NULL,
    CURRENCY         CHAR(3)       NOT NULL DEFAULT 'USD',
    STATUS           VARCHAR(10)   NOT NULL,
    DESCRIPTION      VARCHAR(140),
    FAILURE_REASON   VARCHAR(200),
    INITIATED_BY     BIGINT        NOT NULL,
    CREATED_AT       TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    COMPLETED_AT     TIMESTAMP,
    RECON_LEASE_UNTIL TIMESTAMP,   -- reconciliation claim; only one instance works a row at a time
    CONSTRAINT PK_TRANSACTIONS PRIMARY KEY (ID),
    CONSTRAINT UQ_TXN_REFERENCE UNIQUE (REFERENCE),
    CONSTRAINT UQ_TXN_IDEMPOTENCY UNIQUE (IDEMPOTENCY_KEY),
    CONSTRAINT CK_TXN_TYPE CHECK (TXN_TYPE IN ('TRANSFER', 'DEPOSIT')),
    CONSTRAINT CK_TXN_STATUS CHECK (STATUS IN ('PENDING', 'COMPLETED', 'FAILED')),
    CONSTRAINT CK_TXN_AMOUNT CHECK (AMOUNT > 0)
);

CREATE INDEX NB_TXN.IX_TXN_FROM ON NB_TXN.TRANSACTIONS (FROM_ACCOUNT, CREATED_AT DESC);
CREATE INDEX NB_TXN.IX_TXN_TO   ON NB_TXN.TRANSACTIONS (TO_ACCOUNT, CREATED_AT DESC);
CREATE INDEX NB_TXN.IX_TXN_CREATED ON NB_TXN.TRANSACTIONS (CREATED_AT DESC);
CREATE INDEX NB_TXN.IX_TXN_STATUS ON NB_TXN.TRANSACTIONS (STATUS, CREATED_AT);

-- Saved payees. CUSTOMER_ID is the NB_AUTH user id (no cross schema foreign key, by design).
-- The account number is checked against account-service when the payee is saved.
CREATE TABLE NB_TXN.BENEFICIARIES (
    ID               BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    CUSTOMER_ID      BIGINT        NOT NULL,
    NICKNAME         VARCHAR(60)   NOT NULL,
    ACCOUNT_NUMBER   VARCHAR(12)   NOT NULL,
    CREATED_AT       TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_BENEFICIARIES PRIMARY KEY (ID),
    CONSTRAINT UQ_BENEFICIARY_ACCOUNT UNIQUE (CUSTOMER_ID, ACCOUNT_NUMBER),
    CONSTRAINT CK_BENEFICIARY_ACCOUNT CHECK (LENGTH(ACCOUNT_NUMBER) = 12)
);

-- Transfers, admin deposits, payee changes and reconciliation outcomes (ACTOR_ROLE SYSTEM).
-- Insert only: the service never updates or deletes these rows. One row per state-changing
-- request, successful or not. Reads are not recorded. No passwords, tokens or request bodies.
-- ACTOR_EMAIL on a failed LOGIN is the email that was tried (unverified).
CREATE TABLE NB_TXN.AUDIT_LOG (
    ID               BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    OCCURRED_AT      TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    ACTOR_ID         BIGINT,
    ACTOR_ROLE       VARCHAR(10),
    ACTOR_EMAIL      VARCHAR(120),
    ACTION           VARCHAR(40)   NOT NULL,
    TARGET_TYPE      VARCHAR(20),
    TARGET_ID        VARCHAR(64),
    OUTCOME          VARCHAR(10)   NOT NULL,
    HTTP_STATUS      SMALLINT,
    REASON           VARCHAR(200),
    DETAILS          VARCHAR(1000),
    CORRELATION_ID   VARCHAR(64),
    SOURCE_IP        VARCHAR(200),
    CONSTRAINT PK_TXN_AUDIT PRIMARY KEY (ID),
    CONSTRAINT CK_TXN_AUDIT_OUTCOME CHECK (OUTCOME IN ('SUCCESS', 'FAILURE'))
);

CREATE INDEX NB_TXN.IX_AUDIT_OCCURRED ON NB_TXN.AUDIT_LOG (OCCURRED_AT DESC);
CREATE INDEX NB_TXN.IX_AUDIT_ACTOR    ON NB_TXN.AUDIT_LOG (ACTOR_ID, OCCURRED_AT DESC);
CREATE INDEX NB_TXN.IX_AUDIT_ACTION   ON NB_TXN.AUDIT_LOG (ACTION, OCCURRED_AT DESC);

-- Daily completed volume, used by the admin dashboard chart.
CREATE VIEW NB_TXN.V_DAILY_VOLUME (TXN_DATE, TXN_COUNT, TOTAL_AMOUNT) AS
    SELECT DATE(CREATED_AT), COUNT(*), SUM(AMOUNT)
    FROM NB_TXN.TRANSACTIONS
    WHERE STATUS = 'COMPLETED'
    GROUP BY DATE(CREATED_AT);
