-- =====================================================================
-- NovaBank sample database for IBM Db2 (tested layout for Db2 11.5 / 12.1)
-- Database : NOVABANK
-- Schemas  : NB_AUTH (auth-service), NB_ACCT (account-service), NB_TXN (transaction-service)
--
-- Run as the instance owner:
--   db2 connect to NOVABANK
--   db2 -tvf 01-schema.sql
--   db2 -tvf 02-sample-data.sql
-- Each service owns exactly one schema. Services never read another schema directly.
-- =====================================================================

CREATE SCHEMA NB_AUTH;
CREATE SCHEMA NB_ACCT;
CREATE SCHEMA NB_TXN;

-- ---------------------------------------------------------------------
-- auth-service
-- ---------------------------------------------------------------------
CREATE TABLE NB_AUTH.USERS (
    ID              BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    EMAIL           VARCHAR(120)  NOT NULL,
    PASSWORD_HASH   VARCHAR(100)  NOT NULL,
    FULL_NAME       VARCHAR(120)  NOT NULL,
    PHONE           VARCHAR(20),
    ROLE            VARCHAR(10)   NOT NULL DEFAULT 'CUSTOMER',
    STATUS          VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE',
    CREATED_AT      TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    LAST_LOGIN_AT   TIMESTAMP,
    CONSTRAINT PK_USERS PRIMARY KEY (ID),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_ROLE CHECK (ROLE IN ('ADMIN', 'CUSTOMER')),
    CONSTRAINT CK_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'LOCKED'))
);

CREATE INDEX NB_AUTH.IX_USERS_ROLE ON NB_AUTH.USERS (ROLE, STATUS);

-- Sign-ins (including failed ones), registrations, profile and password changes, admin user changes.
-- Insert only: the service never updates or deletes these rows. One row per state-changing
-- request, successful or not. Reads are not recorded. No passwords, tokens or request bodies.
-- ACTOR_EMAIL on a failed LOGIN is the email that was tried (unverified).
CREATE TABLE NB_AUTH.AUDIT_LOG (
    ID               BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    OCCURRED_AT      TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    ACTOR_ID         BIGINT,
    ACTOR_ROLE       VARCHAR(10),
    ACTOR_EMAIL      VARCHAR(120),
    ACTION           VARCHAR(40)   NOT NULL,
    TARGET_TYPE      VARCHAR(20),
    TARGET_ID        VARCHAR(64),
    OUTCOME          VARCHAR(10)   NOT NULL,
    HTTP_STATUS      SMALLINT,
    REASON           VARCHAR(200),
    DETAILS          VARCHAR(1000),
    CORRELATION_ID   VARCHAR(64),
    SOURCE_IP        VARCHAR(200),
    CONSTRAINT PK_AUTH_AUDIT PRIMARY KEY (ID),
    CONSTRAINT CK_AUTH_AUDIT_OUTCOME CHECK (OUTCOME IN ('SUCCESS', 'FAILURE'))
);

CREATE INDEX NB_AUTH.IX_AUDIT_OCCURRED ON NB_AUTH.AUDIT_LOG (OCCURRED_AT DESC);
CREATE INDEX NB_AUTH.IX_AUDIT_ACTOR    ON NB_AUTH.AUDIT_LOG (ACTOR_ID, OCCURRED_AT DESC);
CREATE INDEX NB_AUTH.IX_AUDIT_ACTION   ON NB_AUTH.AUDIT_LOG (ACTION, OCCURRED_AT DESC);

-- ---------------------------------------------------------------------
-- account-service
-- ---------------------------------------------------------------------
CREATE TABLE NB_ACCT.ACCOUNTS (
    ID              BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ACCOUNT_NUMBER  VARCHAR(12)   NOT NULL,
    CUSTOMER_ID     BIGINT        NOT NULL,
    CUSTOMER_NAME   VARCHAR(120)  NOT NULL,
    ACCOUNT_TYPE    VARCHAR(10)   NOT NULL,
    BALANCE         DECIMAL(15,2) NOT NULL DEFAULT 0,
    CURRENCY        CHAR(3)       NOT NULL DEFAULT 'USD',
    STATUS          VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE',
    OPENED_AT       TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    VERSION         INTEGER       NOT NULL DEFAULT 0,
    CONSTRAINT PK_ACCOUNTS PRIMARY KEY (ID),
    CONSTRAINT UQ_ACCOUNTS_NUMBER UNIQUE (ACCOUNT_NUMBER),
    CONSTRAINT CK_ACCOUNTS_TYPE CHECK (ACCOUNT_TYPE IN ('SAVINGS', 'CHECKING')),
    CONSTRAINT CK_ACCOUNTS_STATUS CHECK (STATUS IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    CONSTRAINT CK_ACCOUNTS_BALANCE CHECK (BALANCE >= 0)
);

CREATE INDEX NB_ACCT.IX_ACCOUNTS_CUSTOMER ON NB_ACCT.ACCOUNTS (CUSTOMER_ID);

-- One row per transaction-service reference. APPLIED is written in the same Db2 transaction
-- as the balance change; VOIDED is written by reconciliation so a late request can never
-- apply. The primary key makes the two mutually exclusive.
CREATE TABLE NB_ACCT.TRANSFER_LEDGER (
    REFERENCE       VARCHAR(24)   NOT NULL,
    OUTCOME         VARCHAR(10)   NOT NULL,
    RECORDED_AT     TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_TRANSFER_LEDGER PRIMARY KEY (REFERENCE),
    CONSTRAINT CK_LEDGER_OUTCOME CHECK (OUTCOME IN ('APPLIED', 'VOIDED'))
);

-- Accounts opened and admin status changes.
-- Insert only: the service never updates or deletes these rows. One row per state-changing
-- request, successful or not. Reads are not recorded. No passwords, tokens or request bodies.
-- ACTOR_EMAIL on a failed LOGIN is the email that was tried (unverified).
CREATE TABLE NB_ACCT.AUDIT_LOG (
    ID               BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    OCCURRED_AT      TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    ACTOR_ID         BIGINT,
    ACTOR_ROLE       VARCHAR(10),
    ACTOR_EMAIL      VARCHAR(120),
    ACTION           VARCHAR(40)   NOT NULL,
    TARGET_TYPE      VARCHAR(20),
    TARGET_ID        VARCHAR(64),
    OUTCOME          VARCHAR(10)   NOT NULL,
    HTTP_STATUS      SMALLINT,
    REASON           VARCHAR(200),
    DETAILS          VARCHAR(1000),
    CORRELATION_ID   VARCHAR(64),
    SOURCE_IP        VARCHAR(200),
    CONSTRAINT PK_ACCT_AUDIT PRIMARY KEY (ID),
    CONSTRAINT CK_ACCT_AUDIT_OUTCOME CHECK (OUTCOME IN ('SUCCESS', 'FAILURE'))
