-- =====================================================================
-- Brings an existing NOVABANK database (dev / preprod VM, or a local Docker
-- volume you do not want to reset) up to date with db2/schema/01-schema.sql
-- for: saved payees, the account-service transfer ledger and reconciliation.
-- Fresh databases do not need this; 01-schema.sql already has everything.
--
--   db2 connect to NOVABANK
--   db2 -tvf db2/migrations/001-beneficiaries-and-reconciliation.sql
--
-- Run it BEFORE deploying the new account-service and transaction-service.
-- =====================================================================

CREATE TABLE NB_TXN.BENEFICIARIES (
    ID               BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    CUSTOMER_ID      BIGINT        NOT NULL,
    NICKNAME         VARCHAR(60)   NOT NULL,
    ACCOUNT_NUMBER   VARCHAR(12)   NOT NULL,
    CREATED_AT       TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_BENEFICIARIES PRIMARY KEY (ID),
    CONSTRAINT UQ_BENEFICIARY_ACCOUNT UNIQUE (CUSTOMER_ID, ACCOUNT_NUMBER),
    CONSTRAINT CK_BENEFICIARY_ACCOUNT CHECK (LENGTH(ACCOUNT_NUMBER) = 12)
);

CREATE TABLE NB_ACCT.TRANSFER_LEDGER (
    REFERENCE       VARCHAR(24)   NOT NULL,
    OUTCOME         VARCHAR(10)   NOT NULL,
    RECORDED_AT     TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_TRANSFER_LEDGER PRIMARY KEY (REFERENCE),
    CONSTRAINT CK_LEDGER_OUTCOME CHECK (OUTCOME IN ('APPLIED', 'VOIDED'))
);

ALTER TABLE NB_TXN.TRANSACTIONS ADD COLUMN RECON_LEASE_UNTIL TIMESTAMP;
CREATE INDEX NB_TXN.IX_TXN_STATUS ON NB_TXN.TRANSACTIONS (STATUS, CREATED_AT);

-- Backfill: every completed transaction moved money, so its reference is APPLIED.
INSERT INTO NB_ACCT.TRANSFER_LEDGER (REFERENCE, OUTCOME, RECORDED_AT)
    SELECT REFERENCE, 'APPLIED', COALESCE(COMPLETED_AT, CREATED_AT)
    FROM NB_TXN.TRANSACTIONS WHERE STATUS = 'COMPLETED';

-- PENDING rows created before this migration have no ledger row even if account-service
-- applied them, so reconciliation would void them and mark them FAILED. List them and
-- settle each one by hand (compare balances) before deploying:
SELECT REFERENCE, TXN_TYPE, FROM_ACCOUNT, TO_ACCOUNT, AMOUNT, CREATED_AT
    FROM NB_TXN.TRANSACTIONS WHERE STATUS = 'PENDING';

COMMIT;
