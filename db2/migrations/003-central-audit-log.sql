-- =====================================================================
-- Brings an existing NOVABANK database (for example a local Docker volume
-- you do not want to reset) up to date with db2/schema/01-schema.sql for:
-- the central audit log (one NB_AUTH.AUDIT_LOG for every service).
-- Fresh databases do not need this; 01-schema.sql already has everything.
--
--   db2 connect to NOVABANK
--   db2 -tvf db2/migrations/003-central-audit-log.sql
--
-- Safe on every database state, and safe to run more than once:
--   * Never had 002:       creates the central table.
--   * Has 002:             moves the per-service tables aside, creates the central table,
--                          COPIES EVERY ROW from NB_AUTH, NB_ACCT and NB_TXN .AUDIT_LOG into it
--                          (OCCURRED_AT becomes CREATED_AT, SERVICE says where it came from),
--                          and only then drops the old tables. No audit row is lost.
--   * Already on 003:      does nothing.
-- It runs as one statement, so if anything fails, Db2 rolls the whole thing back.
--
-- Run it BEFORE starting the new auth-service, account-service and transaction-service.
-- =====================================================================

--#SET TERMINATOR @

BEGIN
    DECLARE v_auth_002 INTEGER DEFAULT 0;   -- NB_AUTH.AUDIT_LOG in the 002 layout (has OCCURRED_AT)
    DECLARE v_central INTEGER DEFAULT 0;    -- NB_AUTH.AUDIT_LOG in the 003 layout (has SERVICE)
    DECLARE v_acct_002 INTEGER DEFAULT 0;
    DECLARE v_txn_002 INTEGER DEFAULT 0;
    DECLARE v_cols VARCHAR(400);

    -- Columns that are the same in 002 and 003 (002's OCCURRED_AT becomes CREATED_AT).
    SET v_cols = 'ACTOR_ID, ACTOR_ROLE, ACTOR_EMAIL, ACTION, TARGET_TYPE, TARGET_ID, OUTCOME, HTTP_STATUS, REASON, DETAILS, CORRELATION_ID, SOURCE_IP';

    SELECT COUNT(*) INTO v_auth_002 FROM SYSCAT.COLUMNS
        WHERE TABSCHEMA = 'NB_AUTH' AND TABNAME = 'AUDIT_LOG' AND COLNAME = 'OCCURRED_AT';
    SELECT COUNT(*) INTO v_central FROM SYSCAT.COLUMNS
        WHERE TABSCHEMA = 'NB_AUTH' AND TABNAME = 'AUDIT_LOG' AND COLNAME = 'SERVICE';
    SELECT COUNT(*) INTO v_acct_002 FROM SYSCAT.TABLES WHERE TABSCHEMA = 'NB_ACCT' AND TABNAME = 'AUDIT_LOG';
    SELECT COUNT(*) INTO v_txn_002 FROM SYSCAT.TABLES WHERE TABSCHEMA = 'NB_TXN' AND TABNAME = 'AUDIT_LOG';

    -- 1. Move the 002 auth table aside. Its index names are needed by the central table.
    IF v_auth_002 = 1 THEN
        EXECUTE IMMEDIATE 'DROP INDEX NB_AUTH.IX_AUDIT_OCCURRED';
        EXECUTE IMMEDIATE 'DROP INDEX NB_AUTH.IX_AUDIT_ACTOR';
        EXECUTE IMMEDIATE 'DROP INDEX NB_AUTH.IX_AUDIT_ACTION';
        EXECUTE IMMEDIATE 'RENAME TABLE NB_AUTH.AUDIT_LOG TO AUDIT_LOG_002';
    END IF;

    -- 2. Create the central table (same definition as db2/schema/01-schema.sql).
    IF v_central = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE NB_AUTH.AUDIT_LOG (
                ID               BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
                CREATED_AT       TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
                SERVICE          VARCHAR(20)   NOT NULL,
                ACTOR_ID         BIGINT,
                ACTOR_ROLE       VARCHAR(10),
                ACTOR_EMAIL      VARCHAR(120),
                ACTION           VARCHAR(40)   NOT NULL,
                TARGET_TYPE      VARCHAR(20),
                TARGET_ID        VARCHAR(64),
                OUTCOME          VARCHAR(10)   NOT NULL,
                HTTP_STATUS      SMALLINT,
                REASON           VARCHAR(200),
                DETAILS          VARCHAR(1000),
                CORRELATION_ID   VARCHAR(64),
                SOURCE_IP        VARCHAR(200),
                CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (ID),
                CONSTRAINT CK_AUDIT_SERVICE CHECK (SERVICE IN (''auth'', ''accounts'', ''transactions'')),
                CONSTRAINT CK_AUDIT_OUTCOME CHECK (OUTCOME IN (''SUCCESS'', ''FAILURE''))
            )';
        EXECUTE IMMEDIATE 'CREATE INDEX NB_AUTH.IX_AUDIT_CREATED ON NB_AUTH.AUDIT_LOG (CREATED_AT DESC)';
        EXECUTE IMMEDIATE 'CREATE INDEX NB_AUTH.IX_AUDIT_ACTOR   ON NB_AUTH.AUDIT_LOG (ACTOR_ID, CREATED_AT DESC)';
        EXECUTE IMMEDIATE 'CREATE INDEX NB_AUTH.IX_AUDIT_ACTION  ON NB_AUTH.AUDIT_LOG (ACTION, CREATED_AT DESC)';
    END IF;

    -- 3. Copy every 002 row in, oldest first, then drop the old table. New IDs are assigned.
    IF v_auth_002 = 1 THEN
        EXECUTE IMMEDIATE 'INSERT INTO NB_AUTH.AUDIT_LOG (CREATED_AT, SERVICE, ' || v_cols || ') '
            || 'SELECT OCCURRED_AT, ''auth'', ' || v_cols || ' FROM NB_AUTH.AUDIT_LOG_002 ORDER BY OCCURRED_AT, ID';
        EXECUTE IMMEDIATE 'DROP TABLE NB_AUTH.AUDIT_LOG_002';
    END IF;
    IF v_acct_002 = 1 THEN
        EXECUTE IMMEDIATE 'INSERT INTO NB_AUTH.AUDIT_LOG (CREATED_AT, SERVICE, ' || v_cols || ') '
            || 'SELECT OCCURRED_AT, ''accounts'', ' || v_cols || ' FROM NB_ACCT.AUDIT_LOG ORDER BY OCCURRED_AT, ID';
        EXECUTE IMMEDIATE 'DROP TABLE NB_ACCT.AUDIT_LOG';
    END IF;
    IF v_txn_002 = 1 THEN
        EXECUTE IMMEDIATE 'INSERT INTO NB_AUTH.AUDIT_LOG (CREATED_AT, SERVICE, ' || v_cols || ') '
            || 'SELECT OCCURRED_AT, ''transactions'', ' || v_cols || ' FROM NB_TXN.AUDIT_LOG ORDER BY OCCURRED_AT, ID';
        EXECUTE IMMEDIATE 'DROP TABLE NB_TXN.AUDIT_LOG';
    END IF;
END@

--#SET TERMINATOR ;

COMMIT;
