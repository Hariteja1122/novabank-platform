-- =====================================================================
-- Brings an existing NOVABANK database (dev / preprod VM, or a local Docker
-- volume you do not want to reset) up to date with db2/schema/01-schema.sql
-- for: the central audit log (one NB_AUTH.AUDIT_LOG for every service).
-- Fresh databases do not need this; 01-schema.sql already has everything.
--
--   db2 connect to NOVABANK
--   db2 -tvf db2/migrations/003-central-audit-log.sql
--
-- Works whether or not 002-audit-log.sql was ever applied:
--   * The three DROP TABLE statements remove the per-service tables from 002. On a
--     database that never had 002 they fail with SQL0204N ("is an undefined name").
--     That is expected and harmless: the Db2 command line carries on with the next statement.
--   * Rows recorded under 002 are discarded. 002 only ever reached local databases.
--
-- Run it BEFORE deploying the new auth-service, account-service and transaction-service.
-- =====================================================================

DROP TABLE NB_ACCT.AUDIT_LOG;
DROP TABLE NB_TXN.AUDIT_LOG;
DROP TABLE NB_AUTH.AUDIT_LOG;

-- Central audit trail for all of NovaBank. auth-service owns it; account-service and
-- transaction-service report their events through POST /internal/audit (internal API key).
-- Insert only. One row per state-changing request, successful or not. Reads are not recorded.
-- No passwords, tokens or request bodies. ACTOR_EMAIL on a failed LOGIN is the email that was tried.
CREATE TABLE NB_AUTH.AUDIT_LOG (
    ID               BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    CREATED_AT       TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    SERVICE          VARCHAR(20)   NOT NULL,
    ACTOR_ID         BIGINT,
    ACTOR_ROLE       VARCHAR(10),
    ACTOR_EMAIL      VARCHAR(120),
    ACTION           VARCHAR(40)   NOT NULL,
    TARGET_TYPE      VARCHAR(20),
    TARGET_ID        VARCHAR(64),
    OUTCOME          VARCHAR(10)   NOT NULL,
    HTTP_STATUS      SMALLINT,
    REASON           VARCHAR(200),
    DETAILS          VARCHAR(1000),
    CORRELATION_ID   VARCHAR(64),
    SOURCE_IP        VARCHAR(200),
    CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (ID),
    CONSTRAINT CK_AUDIT_SERVICE CHECK (SERVICE IN ('auth', 'accounts', 'transactions')),
    CONSTRAINT CK_AUDIT_OUTCOME CHECK (OUTCOME IN ('SUCCESS', 'FAILURE'))
);

CREATE INDEX NB_AUTH.IX_AUDIT_CREATED ON NB_AUTH.AUDIT_LOG (CREATED_AT DESC);
CREATE INDEX NB_AUTH.IX_AUDIT_ACTOR   ON NB_AUTH.AUDIT_LOG (ACTOR_ID, CREATED_AT DESC);
CREATE INDEX NB_AUTH.IX_AUDIT_ACTION  ON NB_AUTH.AUDIT_LOG (ACTION, CREATED_AT DESC);
